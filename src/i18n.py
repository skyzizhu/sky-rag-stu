"""界面多语言支持（i18n）。

设计原则（不影响核心 RAG 架构）：
- 纯 UI 层：只翻译 app.py 的界面字符串。知识内容、领域英文枚举、
  LLM 提示词与向量库数据一律保持不变。
- 零侵入：t(key) 按当前语言查目录，缺失时回退简体中文，再缺失返回 key 本身，
  所以漏翻一个 key 不会报错，只是显示 key。
- 语言偏好存 settings.json 的 language 键，与主题等设置共用同一套持久化。

用法：
    from src.i18n import t, tr
    t("upload.start")                  # 静态文案
    t("sources.title", n=len(sources)) # 带占位符 {n}
    tr(node["name"])                    # 动态文本（流水线进度/节点名）精确匹配翻译
"""

from __future__ import annotations

DEFAULT_LANGUAGE = "zh-CN"
FOLLOW_SYSTEM = "system"  # language 设置的特殊值：跟随浏览器/系统 locale

LANGUAGES = {
    "zh-CN": "简体中文",
    "zh-TW": "繁體中文",
    "en": "English",
    "ja": "日本語",
}
LANGUAGE_ORDER = ["zh-CN", "zh-TW", "en", "ja"]


def locale_to_language(loc: str | None) -> str:
    """浏览器/系统 locale → 支持的语言代码；识别不出回退简体中文。"""
    loc = (loc or "").replace("_", "-").lower()
    if loc.startswith("zh"):
        return "zh-TW" if any(x in loc for x in ("hant", "tw", "hk", "mo")) else "zh-CN"
    if loc.startswith("ja"):
        return "ja"
    if loc.startswith("en"):
        return "en"
    return DEFAULT_LANGUAGE


def browser_language() -> str:
    """当前浏览器 locale 对应的语言（仅限 Streamlit 运行环境内可用）。"""
    try:
        import streamlit as st

        return locale_to_language(st.context.locale)
    except Exception:
        return DEFAULT_LANGUAGE


def current_language() -> str:
    """当前界面语言（永远返回具体语言代码，不返回 system）。

    session 里存的是 "system" 时，按浏览器 locale 实时解析；
    未初始化时同样跟随系统。
    """
    try:
        import streamlit as st

        lang = st.session_state.get("language", FOLLOW_SYSTEM)
    except Exception:
        lang = DEFAULT_LANGUAGE
    if lang not in LANGUAGES:  # system / 异常值 → 按浏览器解析或回退
        return browser_language() if lang == FOLLOW_SYSTEM else DEFAULT_LANGUAGE
    return lang


def t(key: str, **kwargs) -> str:
    """按 key 翻译：当前语言 → 简体中文 → key 本身（三级回退，永不报错）。"""
    text = _CATALOG.get(current_language(), {}).get(key) \
        or _CATALOG[DEFAULT_LANGUAGE].get(key) or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text


def tr(text: str) -> str:
    """翻译来自流水线层的动态文本（进度提示 / 节点名称 / 节点状态）。

    以简体中文原文为键精确匹配；匹配不到就原样返回（核心流水线不发版也能用）。
    """
    if not text:
        return text
    key = _DYNAMIC.get(text)
    if key is None:
        return text
    # 先查动态目录，再回退主目录（dyn.web.* 等状态文案放在主目录）
    return _DYNAMIC_CATALOG.get(current_language(), {}).get(key) \
        or _DYNAMIC_CATALOG[DEFAULT_LANGUAGE].get(key) \
        or _CATALOG.get(current_language(), {}).get(key) \
        or _CATALOG[DEFAULT_LANGUAGE].get(key) or text


# 语言切换不影响领域枚举本身：给 app 层一个便捷函数
def domain_label_i18n(domain: str, with_code: bool = True) -> str:
    """「code · 本地化标签」格式（与原 domain_label 行为一致）。"""
    label = _CATALOG.get(current_language(), {}).get(f"domain.{domain}") \
        or _CATALOG[DEFAULT_LANGUAGE].get(f"domain.{domain}")
    if not label:
        return domain
    return f"{domain} · {label}" if with_code else label


